
#Arithmetic operators are 
# used with numeric values to perform common mathematical operations:
"""
operators    name                                       example
+	         Addition	                                x + y	
-	         Subtraction	                            x - y	
*	         Multiplication	                            x * y	
/	         Division	                                x / y	
%	         Modulus	                                x % y	
**	         Exponentiation	                            x ** y	
//	         Floor division	                            x // y	

"""
x = 15
y = 4

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y)
print(x ** y)
print(x // y)

